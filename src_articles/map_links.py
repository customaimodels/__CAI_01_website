"""Articles map: every page, every clickable thing, in one table.

    python3 src_articles/map_links.py          writes src_articles/MAP.yml, prints drift
    python3 src_articles/map_links.py --check  same, exits 1 on drift

MAP.yml is generated -- read it, never hand-edit it. The pages stay the source for now
(PROPOSAL: the nav + footer move INTO a yml that the pages are built from).
Drift = a page whose nav misses an article, an internal link to nothing, a footer without the Est. 2022 line.
Stdlib only.
"""
import sys
from html.parser import HTMLParser
from pathlib import Path

HERE = Path(__file__).resolve().parent
SITE = HERE.parent
YEAR = "Est. 2022 · © 2026 Custom AI Models"


class Clicks(HTMLParser):
    def __init__(self):
        super().__init__()
        self.title, self.items, self._in, self._a, self._zone = "", [], None, None, []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in ("header", "nav", "main", "article", "footer"):
            self._zone.append(tag)
        if tag == "title":
            self._in = "title"
        if tag in ("a", "button"):
            self._a = {"zone": self._zone[-1] if self._zone else "page", "kind": tag,
                       "href": a.get("href", ""), "text": "", "current": "aria-current" in a}

    def handle_endtag(self, tag):
        if tag in ("header", "nav", "main", "article", "footer") and self._zone:
            self._zone.pop()
        if tag == "title":
            self._in = None
        if tag in ("a", "button") and self._a is not None:
            self._a["text"] = " ".join(self._a["text"].split())
            self.items.append(self._a)
            self._a = None

    def handle_data(self, d):
        if self._in == "title":
            self.title += d
        if self._a is not None:
            self._a["text"] += d


def pages():
    out = [("/articles/", HERE / "index.html")]
    for d in sorted(p for p in HERE.iterdir() if p.is_dir() and (p / "index.html").exists()):
        out.append((f"/articles/{d.name}/", d / "index.html"))
    return out


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(check):
    rows, drift = [], []
    found = pages()
    urls = {u for u, _ in found}
    articles = [u for u, f in found if (f.parent / "meta.json").is_file()]   # an article carries meta.json; region hubs do not
    known = urls | {"/", "/behind-the-models/", "/r-cai/", "/y-vault/", "/recruiter/"}
    for url, f in found:
        html = f.read_text(encoding="utf-8")
        p = Clicks()
        p.feed(html)
        nav = [i for i in p.items if i["zone"] in ("header", "nav")]
        navhrefs = {i["href"].rstrip("/") + "/" for i in nav if i["href"].startswith("/articles/")}
        for a in articles:
            if a not in navhrefs:
                drift.append(f"{url}: nav misses {a}")
        for i in p.items:
            h = i["href"].split("#")[0].split("?")[0]
            if h.startswith("/") and not h.startswith(("/articles/03_img", "/favicon")) and h not in known \
                    and not (SITE / "src_landing" / h.lstrip("/")).exists():
                drift.append(f"{url}: link to nothing {i['href']} ({i['text']})")
        if YEAR not in html:
            drift.append(f"{url}: footer has no '{YEAR}'")
        rows.append((url, f.relative_to(SITE), p.title.strip(), p.items))

    lines = ["# GENERATED by src_articles/map_links.py -- do not edit. Every page, every clickable thing.",
             f"footer_year: {q(YEAR)}", "articles:"]
    lines += [f"  - {u}" for u in articles]
    lines.append("pages:")
    for url, f, title, items in rows:
        lines += [f"  - url: {url}", f"    file: {f}", f"    title: {q(title)}", "    clicks:"]
        for i in items:
            ext = "external" if i["href"].startswith("http") else "internal"
            cur = ", current: true" if i["current"] else ""
            lines.append(f"      - {{zone: {i['zone']}, {i['kind']}: {q(i['text'] or '(icon)')}, "
                         f"href: {q(i['href'])}, to: {ext}{cur}}}")
    lines.append("drift:" + ("" if drift else " []"))
    lines += [f"  - {q(d)}" for d in drift]
    (HERE / "MAP.yml").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"MAP.yml · {len(rows)} pages · {sum(len(r[3]) for r in rows)} clickables · drift {len(drift)}")
    for d in drift:
        print("  ✗", d)
    return 1 if (check and drift) else 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
